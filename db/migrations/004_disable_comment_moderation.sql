-- ============================================================
-- 迁移 004：停用留言审核
--
-- 取消「先审核再显示」之后，新留言直接可见。
-- status 字段**不删**，有两个原因：
--   1. 删列要改所有查询和后台页面，风险大于收益；
--   2. 哪天想恢复审核（比如被灌了广告），把默认值改回 0 再加一句 WHERE 就回来了。
--
-- 历史上处于「待审」的留言一并放行，避免它们永远卡在后台谁也看不到。
-- ============================================================

ALTER TABLE comments
  MODIFY COLUMN status TINYINT NOT NULL DEFAULT 1
    COMMENT '0待审 1通过。审核已停用，恒为 1，字段保留以便将来恢复';

UPDATE comments SET status = 1 WHERE status = 0;
